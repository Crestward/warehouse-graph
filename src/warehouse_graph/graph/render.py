"""Text renderings of the graph: a Mermaid lineage diagram (task 2.8) and docs/graph-stats.md.

Mermaid instead of a PNG: GitHub renders it inline, it needs no plotting dependency, and it is
regenerated from the artifact so it can't go stale (design decision D10).
"""

from __future__ import annotations

from warehouse_graph.graph.artifact import ArtifactMeta
from warehouse_graph.graph.query import Subgraph
from warehouse_graph.graph.schema import NodeType

_SHAPES = {
    NodeType.SOURCE: ('[("', '")]'),
    NodeType.MODEL: ('["', '"]'),
    NodeType.METRIC: ('{{"', '"}}'),
    NodeType.EXPOSURE: ('[/"', '"/]'),
    NodeType.COLUMN: ('("', '")'),
}
_CLASSES = """    classDef source fill:#e8f0fe,stroke:#4a6fa5
    classDef model fill:#f4f4f4,stroke:#666
    classDef metric fill:#e6f4ea,stroke:#3c8d5a
    classDef exposure fill:#fff4e5,stroke:#c77700
    classDef column fill:#fafafa,stroke:#999
    classDef flagged stroke:#c62828,stroke-width:2px,stroke-dasharray:4 2"""


def _key(node_id: str) -> str:
    return node_id.replace(".", "_")


def mermaid(sub: Subgraph) -> str:
    """Left-to-right flowchart: data flows from sources to exposures."""
    lines = ["flowchart LR"]
    for n in sub.nodes:
        start, end = _SHAPES.get(n.type, ('["', '"]'))
        label = n.name + (" ⚠" if n.deprecated or n.trap_kind else "")
        lines.append(f"    {_key(n.id)}{start}{label}{end}:::{n.type.value}")
    for e in sub.edges:
        # Edges point at what a node depends on; draw them in the direction data flows.
        lines.append(f"    {_key(e.target)} --> {_key(e.source)}")
    flagged = [_key(n.id) for n in sub.nodes if n.deprecated or n.trap_kind]
    lines.append(_CLASSES)
    if flagged:
        lines.append(f"    class {','.join(flagged)} flagged")
    return "\n".join(lines)


def stats_markdown(meta: ArtifactMeta) -> str:
    s = meta.stats
    node_rows = "\n".join(f"| {t} | {c} |" for t, c in s.nodes_by_type.items())
    edge_rows = "\n".join(f"| `{t}` | {c} |" for t, c in s.edges_by_type.items())
    unresolved = "\n".join(f"- `{c}`" for c in s.unresolved_columns) or "- none"
    failed = "\n".join(f"- `{m}`: {err}" for m, err in s.lineage_failed_models.items()) or "- none"
    return f"""# Graph stats

Generated by `warehouse-graph build --stats docs/graph-stats.md` from the default demo build
(seed 42). Don't edit by hand.

| | |
|---|---|
| Built | {meta.built_at:%Y-%m-%d %H:%M} UTC, warehouse-graph {meta.warehouse_graph_version} |
| Graph format | v{meta.format_version} |
| Manifest sha256 | `{meta.manifest_sha256[:16]}…` |
| Embedding model | `{meta.embedding_model}` ({meta.embedding_dims} dims, local CPU) |
| Build time | {s.build_seconds} s (artifacts → graph file, incl. embeddings) |
| Nodes | {sum(s.nodes_by_type.values())} |
| Edges | {sum(s.edges_by_type.values())} |

## Nodes
| Type | Count |
|---|---|
{node_rows}

## Edges
| Type | Count |
|---|---|
{edge_rows}

## Column-level lineage (task 2.4: best effort, time-boxed)
**Coverage: {s.column_lineage_coverage:.1%}** ({s.columns_with_upstream} of {s.model_columns} model
columns trace to at least one upstream column via sqlglot).

Models that failed to parse:
{failed}

Columns with no upstream column (literals, generated values, or unresolved):
{unresolved}
"""
